def main():
    probs = validate()
    if probs:
        print('VALIDATION PROBLEMS:'); [print(' ', p) for p in probs]; sys.exit(1)
    out = HERE
    write_palette(out); write_js(out); write_pngs(out); write_preview(out); write_demo(out)
