"""Re-runnable generator for the TBOIQ original pixel-art kit.
All art is hand-authored as text grids in ./src (no image models, no external art).
Outputs: palette.{json,css,png}, PALETTE_NOTES.md, icons.js, icons.mjs, demo.html, manifest.json,
preview.png, items/ characters/ ui/ PNGs (16px / 24px native + 2x nearest '_x2' copies), lint-report.txt.
Usage:  python3 generate.py"""
import os, sys, json, shutil
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, 'src'))
from PIL import Image, ImageDraw, ImageFont
import palette_def, icons_rev, icons_chars, icons_ui

PAL = palette_def.PALETTE
HEX = {k: h for k, h, _, _ in PAL}
RGB = {k: tuple(int(h[i:i+2], 16) for i in (1, 3, 5)) for k, h in HEX.items()}
RAMPS = {
 'void/night (tinted near-blacks)': 'knpP u'.replace(' ', ''),
 'blood reds':      'rReE',
 'bone / cream':    'qmtwW',
 'sickly greens':   'gGlL',
 'dusk purples':    'pPu',
 'iron / night blues': 'bBc',
 'torchlight (warm accent)': 'yYZ',
}
ORDER = [k for k, *_ in PAL]

# ------------------------------------------------------------------ collect icons
ICONS = {}      # name -> dict(category, grid)
CATS = ['passive', 'active', 'trinket', 'familiar']
for (cat, name), g in icons_rev.ICONS.items():
    ICONS[name] = dict(cat=cat, grid=g)
for name, g in icons_chars.CH.items():
    ICONS[name] = dict(cat='character', grid=g)
for name in icons_ui.UI:
    ICONS['ui_' + name] = dict(cat='ui', grid=icons_ui.UI[name], state='normal', base=name)
    ICONS['ui_' + name + '_hover'] = dict(cat='ui', grid=icons_ui.hover(name), state='hover', base=name)

FOLDER = {'passive': 'items/passive', 'active': 'items/active', 'trinket': 'items/trinkets',
          'familiar': 'items/familiars', 'character': 'characters', 'ui': 'ui'}

# ------------------------------------------------------------------ validate
def validate():
    problems = []
    for n, d in ICONS.items():
        g = d['grid']; h = len(g); w = len(g[0]) if g else 0
        if any(len(r) != w for r in g): problems.append(f'{n}: ragged rows')
        exp = (24 if d['cat'] == 'character' else 16)
        if (w, h) != (exp, exp): problems.append(f'{n}: size {w}x{h}, expected {exp}')
        for y, r in enumerate(g):
            for x, c in enumerate(r):
                if c != '.' and c not in HEX: problems.append(f'{n}: bad key {c!r} at {x},{y}')
        # orphan = opaque pixel with no 8-neighbour opaque pixel
        for y, r in enumerate(g):
            for x, c in enumerate(r):
                if c == '.': continue
                nb = [g[y+dy][x+dx] for dy in (-1,0,1) for dx in (-1,0,1)
                      if (dx or dy) and 0 <= y+dy < h and 0 <= x+dx < w]
                if all(v == '.' for v in nb): problems.append(f'{n}: orphan pixel at {x},{y}')
    return problems

def to_img(grid, scale=1):
    h, w = len(grid), len(grid[0])
    im = Image.new('RGBA', (w, h), (0, 0, 0, 0))
    for y, r in enumerate(grid):
        for x, c in enumerate(r):
            if c != '.': im.putpixel((x, y), RGB[c] + (255,))
    return im.resize((w*scale, h*scale), Image.NEAREST) if scale > 1 else im

# ------------------------------------------------------------------ colour maths
def lum(rgb):
    def f(v):
        v /= 255; return v/12.92 if v <= 0.03928 else ((v+0.055)/1.055) ** 2.4
    r, g, b = rgb; return 0.2126*f(r) + 0.7152*f(g) + 0.0722*f(b)
def contrast(a, b):
    la, lb = lum(RGB[a]), lum(RGB[b]); hi, lo = max(la, lb), min(la, lb)
    return (hi + 0.05) / (lo + 0.05)

# ------------------------------------------------------------------ palette outputs
def write_palette(out):
    data = {'name': 'TBOIQ Dungeon-24', 'count': len(PAL),
            'colors': [{'key': k, 'hex': h, 'name': n, 'role': r,
                        'contrast_on_k': round(contrast(k, 'k'), 2), 'contrast_on_n': round(contrast(k, 'n'), 2)}
                       for k, h, n, r in PAL],
            'ramps': {n: list(v) for n, v in RAMPS.items()}}
    json.dump(data, open(f'{out}/palette.json', 'w'), indent=2)
    names = {'k':'void','n':'night','p':'violet-deep','P':'violet','u':'violet-lit','b':'blue-deep','B':'blue','c':'blue-lit',
             'r':'blood-deep','R':'blood-dry','e':'blood','E':'blood-lit','q':'bone-deep','m':'bone-shadow','t':'bone','w':'bone-lit','W':'cream',
             'g':'green-deep','G':'green','l':'green-lit','L':'green-hi','y':'torch-deep','Y':'torch','Z':'flame'}
    css = ['/* TBOIQ Dungeon-24 palette - generated by generate.py */', ':root {']
    for k, h, n, r in PAL: css.append(f'  --tb-{names[k]}: {h};   /* {k} - {n}: {r} */')
    css.append('}')
    css += ['', '.tb-bg      { background: var(--tb-void); color: var(--tb-cream); }',
            '.tb-panel   { background: var(--tb-night); border: 2px solid var(--tb-violet-deep); }',
            '.tb-text-dim{ color: var(--tb-bone); }',
            '.tb-danger  { color: var(--tb-blood-lit); }',
            '.tb-ok      { color: var(--tb-green-hi); }',
            '.tb-accent  { color: var(--tb-flame); }',
            '/* pixel art images / canvases: always crisp */',
            '.tb-px, canvas.tb-px, img.tb-px { image-rendering: pixelated; image-rendering: crisp-edges; }',
            '/* icon-only buttons: normal = bone, hover/active = torchlight (swap to the *_hover icon) */',
            '.tb-icon-btn { background: var(--tb-night); border: 2px solid var(--tb-violet-deep); padding: 4px; cursor: pointer; }',
            '.tb-icon-btn:hover, .tb-icon-btn:focus-visible, .tb-icon-btn[aria-pressed="true"] { border-color: var(--tb-torch); outline: none; }']
    open(f'{out}/palette.css', 'w').write('\n'.join(css) + '\n')
    # swatch png
    font = ImageFont.load_default()
    cell, cols = 96, 6; rows = (len(PAL) + cols - 1) // cols
    ramp_h = 150
    im = Image.new('RGB', (cols*cell, rows*cell + ramp_h), RGB['n']); d = ImageDraw.Draw(im)
    for i, (k, h, n, r) in enumerate(PAL):
        x, y = (i % cols)*cell, (i // cols)*cell
        d.rectangle([x, y, x+cell-1, y+cell-1], fill=RGB[k])
        fg = RGB['W'] if lum(RGB[k]) < 0.3 else RGB['k']
        d.text((x+6, y+6), f'{k}  {h}', fill=fg, font=font); d.text((x+6, y+22), n, fill=fg, font=font)
    y = rows*cell + 8
    for name, keys in RAMPS.items():
        d.text((8, y), name, fill=RGB['w'], font=font)
        for j, k in enumerate(keys): d.rectangle([260 + j*40, y-2, 260 + j*40 + 36, y + 14], fill=RGB[k])
        y += 20
    im.save(f'{out}/palette.png')
    # notes
    L = ['# TBOIQ Dungeon-24 - palette notes', '',
         '24 colours, every ramp hue-shifted (shadows slide toward violet/blue, highlights toward yellow/orange).',
         'There is **no pure black** and no pure white: darkest `#0e0b14` carries a violet tint, brightest `#f5ebcf` is warm cream.', '',
         '| key | hex | name | role | contrast vs k | vs n |', '|---|---|---|---|---|---|']
    for k, h, n, r in PAL:
        L.append(f'| `{k}` | `{h}` | {n} | {r} | {contrast(k,"k"):.1f} | {contrast(k,"n"):.1f} |')
    L += ['', '## Ramps', ''] + [f'- **{n}**: ' + ' -> '.join(f'`{k}`' for k in v) for n, v in RAMPS.items()]
    L += ['', '## Contrast and usage', '',
          '- Page background: `k` (#0e0b14). Cards/panels: `n` (#17121f) with a `p` border; use `P`/`u` only for hovered panels.',
          f'- Body text: `W` on `n` = {contrast("W","n"):.1f}:1, `w` on `n` = {contrast("w","n"):.1f}:1 (both AAA). Secondary text `t` on `n` = {contrast("t","n"):.1f}:1 (AA for normal text).',
          f'- Never set text in `m`, `q`, `p`, `P`, `b`, `r`, `R` on dark panels: they fall below 4.5:1 (`m` on `n` = {contrast("m","n"):.1f}:1). They are for outlines and shadows only.',
          f'- Accent / hover: `Z` flame {contrast("Z","n"):.1f}:1, `Y` torchlight {contrast("Y","n"):.1f}:1 on `n`. Use `Y` for focus rings and hovered icons, `Z` for tiny sparks and the single most important highlight per screen.',
          f'- Correct = `L`/`l` on `n` ({contrast("L","n"):.1f}:1 / {contrast("l","n"):.1f}:1). Wrong = `E` on `n` ({contrast("E","n"):.1f}:1); `e` is only {contrast("e","n"):.1f}:1, so use it for fills, not text.',
          '- Colour-blind safety: never rely on red vs green alone; correct/wrong icons differ in shape (check vs X).',
          '- Limit any single sprite to 3-4 tones of one ramp + a dark outline tone of the same ramp. Outlines: bone -> `q`, red -> `r`, green -> `g`, purple -> `p`, blue/steel -> `b`, torch/gold -> `R`. `k` is reserved for voids (pupils, keyholes, eye sockets, pips).',
          '- Lighting is always top-left: highlight tone on upper-left edges, shadow tone on lower-right edges.',
          '- Icon-only UI: normal state = bone ramp (`W w t` + `m` outline); hover/active = torch ramp (`Z Y y` + `R` outline). Correct/wrong keep their hue and just brighten.']
    open(f'{out}/PALETTE_NOTES.md', 'w').write('\n'.join(L) + '\n')

# ------------------------------------------------------------------ js outputs
def js_icons():
    lines = []
    for cat in CATS + ['character', 'ui']:
        for n, d in ICONS.items():
            if d['cat'] == cat:
                lines.append(f"  {json.dumps(n)}: [\n" + ',\n'.join('    ' + json.dumps(r) for r in d['grid']) + '\n  ]')
    return ',\n'.join(lines)

JS_BODY = '''
// ---- TBOIQ original pixel-art kit: palette + icons (generated by generate.py) ----
// Each icon = array of N strings (N=16 for items/UI, 24 for characters), one char per pixel.
// '.' = transparent, any other char is a key into PALETTE.
const PALETTE = %(pal)s;

const ICONS = {
%(icons)s
};

const CATEGORIES = %(cats)s;

// Draw one icon with nearest-neighbour scaling (no smoothing, zero partial alpha).
function drawIcon(ctx, icon, x, y, scale) {
  scale = scale || 1;
  ctx.imageSmoothingEnabled = false;
  const sheet = typeof icon === 'string' ? ICONS[icon] : icon;
  for (let py = 0; py < sheet.length; py++) {
    const row = sheet[py];
    for (let px = 0; px < row.length; px++) {
      const ch = row[px];
      if (ch === '.') continue;
      ctx.fillStyle = PALETTE[ch];
      ctx.fillRect(x + px * scale, y + py * scale, scale, scale);
    }
  }
}

// Convenience: make a canvas element sized for an icon (CSS pixelated).
function iconCanvas(icon, scale) {
  const sheet = typeof icon === 'string' ? ICONS[icon] : icon;
  const c = document.createElement('canvas');
  c.width = sheet[0].length * (scale || 1); c.height = sheet.length * (scale || 1);
  c.className = 'tb-px'; c.style.imageRendering = 'pixelated';
  drawIcon(c.getContext('2d'), sheet, 0, 0, scale || 1);
  return c;
}
'''
def write_js(out):
    body = JS_BODY % dict(pal=json.dumps({k: HEX[k] for k in ORDER}, indent=2),
                          icons=js_icons(),
                          cats=json.dumps({c: [n for n, d in ICONS.items() if d['cat'] == c] for c in CATS + ['character', 'ui']}, indent=2))
    umd = ('(function (root, factory) {\n  var api = factory();\n  if (typeof module === "object" && module.exports) module.exports = api;\n'
           '  else root.TBOIQ = api;\n})(typeof self !== "undefined" ? self : this, function () {' + body.replace('\n', '\n  ') +
           '\n  return { PALETTE: PALETTE, ICONS: ICONS, CATEGORIES: CATEGORIES, drawIcon: drawIcon, iconCanvas: iconCanvas };\n});\n')
    open(f'{out}/icons.js', 'w').write(umd)
    open(f'{out}/icons.mjs', 'w').write(body.replace('const PALETTE', 'export const PALETTE').replace('const ICONS', 'export const ICONS')
                                        .replace('const CATEGORIES', 'export const CATEGORIES').replace('function drawIcon', 'export function drawIcon')
                                        .replace('function iconCanvas', 'export function iconCanvas'))

# ------------------------------------------------------------------ png + manifest
def pretty(n): return n.replace('ui_', '').replace('_', ' ')
def write_pngs(out):
    for sub in ('items', 'characters', 'ui'):
        shutil.rmtree(f'{out}/{sub}', ignore_errors=True)
    man = []
    for n, d in ICONS.items():
        folder = f"{out}/{FOLDER[d['cat']]}"; os.makedirs(folder, exist_ok=True)
        im = to_img(d['grid']); size = im.size[0]
        fname = n[3:] if d['cat'] == 'ui' else n
        im.save(f'{folder}/{fname}.png')
        to_img(d['grid'], 2).save(f'{folder}/{fname}_x2.png')
        e = dict(name=n, label=pretty(n), category=d['cat'], size=[size, size],
                 png=f"{FOLDER[d['cat']]}/{fname}.png", png_x2=f"{FOLDER[d['cat']]}/{fname}_x2.png", size_x2=[size*2, size*2])
        if d['cat'] == 'ui': e.update(state=d['state'], base=d['base'])
        man.append(e)
    json.dump({'name': 'TBOIQ original pixel kit', 'palette': 'palette.json', 'script': 'icons.js',
               'counts': {c: sum(1 for e in man if e['category'] == c) for c in CATS + ['character', 'ui']},
               'icons': man}, open(f'{out}/manifest.json', 'w'), indent=2)

def write_preview(out):
    font = ImageFont.load_default()
    S16, S24 = 6, 6
    pad = 14; cols = 8
    secs = [('PASSIVE ITEMS', 'passive'), ('ACTIVE ITEMS', 'active'), ('TRINKETS', 'trinket'), ('FAMILIARS', 'familiar'),
            ('CHARACTERS (24x24)', 'character'), ('UI - normal / hover', 'ui')]
    W = cols * (24*S24 + pad) + pad
    # compute height
    y = pad; plan = []
    for title, cat in secs:
        names = [n for n, d in ICONS.items() if d['cat'] == cat]
        if cat == 'ui': names = [n for n in names if not n.endswith('_hover')]
        size = 24 if cat == 'character' else 16
        sc = 6 if cat != 'ui' else 6
        cw = size*sc + pad; ch = size*sc + (28 if cat != 'ui' else 16*sc + 36)
        rows = (len(names) + cols - 1) // cols
        plan.append((title, cat, names, size, sc, cw, ch, y)); y += 22 + rows*ch + 10
    im = Image.new('RGB', (W, y), RGB['k']); d = ImageDraw.Draw(im)
    for title, cat, names, size, sc, cw, ch, y0 in plan:
        d.text((pad, y0), title, fill=RGB['Y'], font=font)
        for i, n in enumerate(names):
            x = pad + (i % cols) * (24*S24 + pad); y = y0 + 20 + (i // cols) * ch
            d.rectangle([x-3, y-3, x + size*sc + 2, y + size*sc + 2], fill=RGB['n'])
            t = to_img(ICONS[n]['grid'], sc); im.paste(t, (x, y), t)
            if cat == 'ui':
                y2 = y + size*sc + 8
                d.rectangle([x-3, y2-3, x + size*sc + 2, y2 + size*sc + 2], fill=RGB['n'])
                t = to_img(ICONS[n + '_hover']['grid'], sc); im.paste(t, (x, y2), t)
                d.text((x, y2 + size*sc + 6), pretty(n), fill=RGB['t'], font=font)
            else:
                d.text((x, y + size*sc + 8), pretty(n), fill=RGB['t'], font=font)
    im.save(f'{out}/preview.png')

