"""24x24 character busts (original generic silhouettes), authored as left halves (12 cols)."""
from icons_rev import *

INV = {'p':'P','P':'u','b':'B','B':'c','q':'m','m':'t','g':'G','G':'l','r':'R','R':'e','y':'Y','k':'p'}
def rim(grid, skip='k.'):
    """rim-light: outermost right pixel of each row steps one tone lighter (keeps dark busts readable)."""
    out = []
    for r in grid:
        xs = [x for x, c in enumerate(r) if c != '.']
        row = list(r)
        if xs:
            x = xs[-1]; row[x] = INV.get(row[x], row[x])
        out.append(''.join(row))
    return out

